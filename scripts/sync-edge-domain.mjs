// Deno cannot resolve the @finance-tracker/domain workspace package, so Edge
// Functions import a generated copy of selected domain files instead.
// Usage: node scripts/sync-edge-domain.mjs         (write)
//        node scripts/sync-edge-domain.mjs --check (exit 1 on drift)
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'packages/domain/src';
const TARGET = 'supabase/functions/_shared/domain';
const FILES = ['money.ts', 'receipt-evidence.ts'];
const RELATIVE_IMPORT = /from '(\.\.?\/[^']+?)(?<!\.ts)'/g;

const header = (file) =>
  `// GENERATED by scripts/sync-edge-domain.mjs from ${SOURCE}/${file}. Do not edit.\n\n`;

function transform(file, source) {
  const normalized = source.replace(/\r\n/g, '\n');
  return header(file) + normalized.replace(RELATIVE_IMPORT, "from '$1.ts'");
}

async function readOptional(filePath) {
  try {
    return await readFile(filePath, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

async function main() {
  const check = process.argv.includes('--check');
  const drift = [];

  if (!check) await mkdir(path.join(ROOT, TARGET), { recursive: true });

  for (const file of FILES) {
    const source = await readFile(path.join(ROOT, SOURCE, file), 'utf8');
    const expected = transform(file, source);
    const targetPath = path.join(ROOT, TARGET, file);

    if (check) {
      const actual = await readOptional(targetPath);
      if (actual?.replace(/\r\n/g, '\n') !== expected) drift.push(`${TARGET}/${file}`);
    } else {
      await writeFile(targetPath, expected, 'utf8');
      console.log(`wrote ${TARGET}/${file}`);
    }
  }

  if (drift.length > 0) {
    console.error('Edge domain copy is out of date. Run `npm run sync:edge-domain`.');
    for (const file of drift) console.error(`  drift: ${file}`);
    process.exit(1);
  }
  if (check) console.log(`Edge domain copy is in sync (${FILES.length} files).`);
}

await main();
